# 数据存储容器概念
# 数据容器（Container）是一种可以存放多个元素的"容器"，用于把一组相关的数据组织在一起。
# 它解决的是"一个变量名装不下多条数据"的问题，让数据可以批量存储、批量操作。
# Python 中常用的数据容器主要有五种：
#   1. 列表（list）   —— 有序、可变、可重复，用 []
#   2. 字符串（str）  —— 有序、不可变、可重复，用 "" 或 ''
#   3. 元组（tuple）  —— 有序、不可变、可重复，用 ()
#   4. 集合（set）    —— 无序、可变、不重复，用 {}
#   5. 字典（dict）   —— 无序（3.7+ 保留插入顺序）、可变、键不重复，用 {key: value}
# 不同容器之间的区别，主要围绕三点判断：
#   - 是否有序：元素是否有确定的先后顺序（能否用下标访问）
#   - 是否可变：能否在创建后增删改元素
#   - 是否去重：是否允许重复元素存在


# 列表（List）
# 列表是最常用的数据容器，用 [] 定义，内部元素用逗号分隔。
# 元素类型可以不同，这一点与java和c区别真的很大呢。
# 关键语法点：
#   - 有序：元素有固定顺序，支持下标（从 0 开始）和切片。
#   - 可变：可以增、删、改元素。
#   - 可重复：允许出现相同元素。
#   - 支持嵌套：列表里可以再放列表。
# 基本格式：
#   my_list = [元素1, 元素2, 元素3]
# 【举个例子】
character = ["魔理沙", "灵梦", "东风谷早苗", "十六夜咲夜", "爱丽丝", "铃仙"]
print(character[0])          # 魔理沙，下标从 0 开始
print(character[-1])         # 铃仙，-1 表示最后一个。这是python特有的反向索引，从最后开始向前索引
print("---------------------------------------")

# 嵌套列表
matrix = [[1, 2, 3], ["鸿蒙方舟", "天堂之风", "熵"]]
print(matrix[1][2])          # 熵
print("---------------------------------------")

# 修改元素
character[2] = "琪露诺"        # 修改指定索引的元素
print(character[2])
del character[0]              # 删除指定索引的元素
for i in character:
    print(i)
print("---------------------------------------")

# 切片
# 切片是指对操作的数据截取其中一部分的操作。列表、字符串、元组都可以进行切片操作。
# 序列数据[开始索引:结束索引:步长]
print(character[0:3])          # ['灵梦', '琪露诺', '十六夜咲夜']，切片不含结束位置
print(character[-4:-1])        # ['琪露诺', '十六夜咲夜', '爱丽丝']，可以反向索引
# 如果不写步长，则默认为1
print("---------------------------------------")

# 常用方法
# 末尾追加，返回 None
character.append("古明地觉")   
for i in character:
    print(i)
print("---------------------------------------")
# 指定位置插入
print("在0位置插入八云紫")
character.insert(0, "八云紫")  
for i in character:
    print(i)
print("---------------------------------------")
# 按值删除第一个匹配项
print("移除第一个灵梦")
character.remove("灵梦")       
for i in character:
    print(i)
print("---------------------------------------")
# 弹出并返回指定元素，未指定则固定为最后一个
print("弹出第二个元素")
popped = character.pop(2)       
print(popped)
for i in character:
    print(i)
print("---------------------------------------")
# 对列表进行排序，列表中元素的数据类型必须一致
print("对列表元素进行排序")
character.sort()
for i in character:
    print(i)
print("---------------------------------------")
# 反转列表元素
print("对列表进行反转")
character.sort()
for i in character:
    print(i)
print("---------------------------------------")
# 元素个数
print("打印列表的元素个数")
length = len(character)        
print(length)
print("---------------------------------------")

# 【注意事项】
#   1. append 是原地修改并返回 None，不要写 character = character.append(x)。
#   2. 列表是可变对象，赋值 b = a 只是引用同一对象，改 b 会影响 a；
#      想要独立副本要用切片 a[:] 或 a.copy()。
#   3. 下标越界会报 IndexError，访问前注意长度。
#   4. 切片会生成新列表，不改变原列表。
#   5. 仅在列表知识点范围内，对于del和pop()，除了pop方法可以弹出被删除的元素外，二者还有其他差别。del list[a:b]可以删除一个切片，一次性删除多个元素。


# 字符串（String）
# 字符串是用引号包裹的字符序列，属于"字符的容器"，可通过下标和切片访问。
# 关键语法点：
#   - 有序：可用下标、切片。
#   - 不可变：创建后不能修改，任何"修改"其实都生成了新字符串。
#   - 可重复：允许相同字符。
#   - 支持遍历：可用 for 逐个取字符。
# 基本格式：
#   s = "内容"
# 【举个例子】
msg = "我是东风谷早苗"
print(msg[0])            # 我
print(msg[-1])           # 苗
print(msg[2:5])          # 东风谷
print(len(msg))          # 6，字符个数
# 常用方法
s = " Hello World "
print(s.strip())             # 去除首尾空白
print(s.upper())             # 转大写
print("World" in s)          # True，判断子串是否存在
print(s.replace("World", "Python"))   # 替换后返回新字符串
print(s.split())             # 按空白拆分得到列表 ['Hello', 'World']
print("abc".join(["1", "2", "3"]))    # '1abc2abc3'
# 格式化输出
name = "灵梦"
age = 114
print(f"姓名：{name}，年龄：{age}")    # f-string，最推荐
# 【注意事项】
#   1. 字符串不可变，msg[0] = "你" 会报 TypeError。
#   2. 所有"修改类"方法（replace/upper/strip 等）都返回新字符串，原串不变。
#   3. 下标从 0 开始，越界报 IndexError。
#   4. 三引号 """...""" 可表示多行字符串。


# 元组（Tuple）
# 元组用 () 定义，是有序、不可变的数据容器，适合存放"不希望被修改"的数据。
# 关键语法点：
#   - 有序：支持下标、切片、遍历。
#   - 不可变：创建后不能增删改，比列表更安全、更省内存。
#   - 可重复：允许相同元素。
#   - 可以解包：a, b = (1, 2)。
# 基本格式：
#   my_tuple = (元素1, 元素2, 元素3)
# 【举个例子】
location = ("博丽神社", "魔法森林", "地灵殿")
print(location[0])       # 博丽神社
print(location[-1])      # 地灵殿
# 单元素元组必须加逗号
single = (1,)            # 是元组
not_tuple = (1)          # 其实是整数 1
# 解包
name, place, age = ("八云紫", "幻想乡", 17)
print(name, place, age)
# 元组里若有可变元素（如列表），其内部仍可变
t = (1, [2, 3])
t[1].append(4)           # 合法！修改的是列表内容，不是元组元素引用
print(t)                 # (1, [2, 3, 4])
# 【注意事项】
#   1. 元组不可变，t[0] = x 会报 TypeError。
#   2. 单元素元组必须写 (x,)，漏掉逗号就变成普通括号运算。
#   3. 元组比列表更轻量，函数返回多值默认就是元组。
#   4. 一旦元组内含有可变对象，该对象的内容是可以被修改的（浅不可变）。


# 集合（Set）
# 集合用 {} 定义，是无序、可变、元素不重复的容器，常用于"去重"和"集合运算"。
# 关键语法点：
#   - 无序：没有下标，不能按位置访问。
#   - 可变：可以增删元素。
#   - 去重：自动去除重复元素。
#   - 元素必须可哈希（hashable）：不能放列表、字典等可变对象。
# 基本格式：
#   my_set = {元素1, 元素2, 元素3}
# 【举个例子】
# 去重
nums = {1, 2, 2, 3, 3, 3}
print(nums)              # {1, 2, 3}
# 创建空集合只能用 set()，{} 是空字典
empty = set()
# 常用操作
s = set()
s.add("魔理沙")          # 添加元素
s.add("灵梦")
s.discard("魔理沙")      # 删除元素（不存在不报错）
print("灵梦" in s)       # True，成员判断
# 集合运算
a = {1, 2, 3}
b = {3, 4, 5}
print(a & b)            # {3}      交集
print(a | b)            # {1,2,3,4,5}  并集
print(a - b)            # {1, 2}   差集
print(a ^ b)            # {1,2,4,5}  对称差集
# 列表去重常用技巧
lst = [1, 1, 2, 2, 3]
unique = list(set(lst))  # 注意：会打乱原有顺序
# 【注意事项】
#   1. 集合无序，不能用下标访问，也不能保证遍历顺序。
#   2. 空集合是 set()，不是 {}（{} 是空字典）。
#   3. 集合元素必须是可哈希的不可变类型，不能放列表/字典。
#   4. 用集合可以去重，但会丢失原始顺序；需要保序可用 dict.fromkeys()。


# 字典（Dictionary）
# 字典用 {key: value} 定义，是"键值对"容器，通过键（key）快速查找值（value）。
# 关键语法点：
#   - 键唯一：同一个键只能出现一次，后出现的会覆盖前面的。
#   - 键必须可哈希：可用字符串、数字、元组；不能用列表。
#   - 可变：可以增删改键值对。
#   - 3.7+ 起保留插入顺序。
# 基本格式：
#   my_dict = {键1: 值1, 键2: 值2}
# 【举个例子】
person = {"name": "八云紫", "age": 17, "home": "幻想乡"}
print(person["name"])           # 八云紫
print(person.get("job", "无业")) # get 取值，键不存在返回默认值（不报错）
# 增删改
person["job"] = "隙间使者"       # 键不存在则新增
person["age"] = 18               # 键存在则修改
del person["home"]               # 删除键值对
# 常用方法
print(person.keys())            # 所有键
print(person.values())          # 所有值
print(person.items())           # 所有键值对
# 遍历字典
for key, value in person.items():
    print(f"{key} -> {value}")
# 嵌套字典
school = {
    "红魔馆": {"主人": "蕾米莉亚", "地点": "雾之湖"},
    "地灵殿": {"主人": "古明地觉", "地点": "地下"},
}
print(school["红魔馆"]["主人"])   # 蕾米莉亚
# 【注意事项】
#   1. 用 d[key] 取不存在的键会报 KeyError，安全取值用 d.get(key, 默认值)。
#   2. 键必须唯一且可哈希，值可以是任意类型。
#   3. 遍历字典默认遍历的是"键"，取键值对要用 .items()。
#   4. 不要边遍历边修改字典大小，可能报 RuntimeError。


# 五种数据容器对比
#   容器    定义符号      有序   可变   可重复   下标访问   典型场景
#   list    []          是     是     是       是        有序可变的一组数据
#   str     ""/''       是     否     是       是        文本/字符序列
#   tuple   ()          是     否     是       是        不希望被修改的定长数据
#   set     {}          否     是     否       否        去重、成员判断、集合运算
#   dict    {k: v}      否*    是     键唯一   按键      键值映射、快速查找
#  注：dict 在 3.7+ 保留插入顺序，但仍按"键"访问而非下标。


# 通用操作（五大容器通用）
#   1. len(容器)          求元素个数
#   2. 容器 in 元素        判断元素是否存在（dict 判断的是键）
#   3. for 变量 in 容器    遍历
#   4. max()/min()/sum()   求最大/最小/求和（要求元素可比较/可相加）
#   5. 容器转换：list()/tuple()/set()/str()/dict()
# 【举个例子】
data = [3, 1, 4, 1, 5, 9, 2, 6]
print(len(data))        # 8
print(max(data))        # 9
print(sorted(data))     # [1, 1, 2, 3, 4, 5, 6, 9]，返回新列表
print(sum(data))        # 31
# 相互转换
print(list("abc"))      # ['a', 'b', 'c']
print(tuple([1, 2]))    # (1, 2)
print(set([1, 1, 2]))   # {1, 2}
# 【注意事项】
#   1. sorted() 返回新容器，sort() 是列表方法、原地排序返回 None。
#   2. sum()/max()/min() 对 dict 默认作用于"键"。
#   3. 集合之间以及 set 与不可哈希元素无法直接比较大小。






# 【补充知识点】
# 1.序列类型：容器中的元素按特定顺序排列的，可通过索引访问的容器类型称之为序列。比如列表就是一个序列。

# 容器选择的判断思路（注意事项汇总）
#   1. 需要"顺序 + 可修改" → 列表 list。
#   2. 需要"顺序 + 不可修改" → 元组 tuple 或字符串 str。
#   3. 需要"去重 / 集合运算 / 快速成员判断" → 集合 set。
#   4. 需要"键值映射 / 按键快速查找" → 字典 dict。
#   5. 可变容器（list/set/dict）赋值默认是引用传递，共享同一对象；
#      需要独立副本时用 copy()、切片或深拷贝 copy.deepcopy()。
#   6. 分清"可变 vs 不可变"是理解赋值、传参和默认参数陷阱的关键。
#   7. 嵌套结构（列表套字典、字典套列表等）是组织复杂数据的常用方式。