# 运算符概念
# 运算符（Operator）是用于对数据进行运算的特殊符号。它连接一个或多个操作数（Operand），按照一定规则计算并返回结果。
# 例如：a + b 中，"+" 是运算符，a 和 b 是操作数。

# Python 基础运算符按功能大致可分为以下几类：
#   1. 算术运算符
#   2. 赋值运算符
#   3. 比较（关系）运算符
#   4. 逻辑运算符

# 此外还有两个重要概念贯穿始终：
#   - 表达式（Expression）：由运算符和操作数组成的式子，会产生一个值。
#   - 运算符优先级（Precedence）：决定复杂表达式中各运算的执行顺序。


# 算术运算符（Arithmetic Operators）
# 算术运算符用于进行基本的数学运算，是最常用的一类运算符。

#   +    加法：两数相加；对字符串/列表/元组表示"拼接"
#   -    减法：两数相减；对集合表示"差集"
#   *    乘法：两数相乘；对字符串/列表/元组表示"重复"
#   /    除法：结果永远是浮点数（真除法），如 7 / 2 == 3.5
#   //   整除（地板除）：向下取整，丢弃小数部分，如 7 // 2 == 3 ；负数时向下取整：-7 // 2 == -4（注意不是 -3）
#   %    取模（求余数）：7 % 2 == 1；也可用于判断奇偶、循环取值
#   **   幂运算：2 ** 3 == 8；注意幂运算是右结合，2 ** 3 ** 2 == 2 ** 9 == 512

# 【举个例子】
print( "10 + 10 = ", 10 + 4 )
print( "10 - 3 =  ", 10 - 3 )
print( "10 * 2 = ", 10 * 2 )
print( "10 / 6 = ", 10 / 6 )
print( "10 // 3 = ", 10 // 3 )
print( "10 % 4 = ", 10 % 4)
print( "10 ** 8 = ",10 ** 8)

# 【注意事项】
#   1. / 与 // 不同：/ 永远返回 float；// 返回向下取整的结果（可能是 int 或 float）。
#   2. 0 不能作除数：1 / 0 会抛出 ZeroDivisionError。
#   3. 负数整除与取模遵循"向下取整"规则：-7 // 2 == -4，-7 % 2 == 1。
#   4. 混合类型运算（int 与 float）结果通常为 float。
#   5. 字符串/列表的 * 只能与整数相乘，如 "a" * 3 == "aaa"。


# 赋值运算符（Assignment Operators）
# 赋值运算符用于把值赋给变量，其中"复合赋值运算符"是算术运算与赋值的简写。

#   =     基本赋值：x = 10
#   +=    加法赋值：x += 3  等价于  x = x + 3
#   -=    减法赋值：x -= 3  等价于  x = x - 3
#   *=    乘法赋值：x *= 3  等价于  x = x * 3
#   /=    除法赋值：x /= 3  等价于  x = x / 3
#   //=   整除赋值：x //= 3  等价于  x = x // 3
#   %=    取模赋值：x %= 3  等价于  x = x % 3
#   **=   幂赋值  ：x **= 3  等价于  x = x ** 3

# 【举个例子】
num = 3
print( "num = ", num )
num += 3
print( "num = ", num )
num -= 2
print( "num = ", num )
num *= 10
print( "num = ", num )
num /= 2
print( "num = ", num )
num //= 3
print( "num = ", num )
num %= 4
print( "num = ", num )
# 【注意事项】
#   1. 复合赋值对可变对象（如列表）有原地修改的效果，如 lst += [1] 会原地扩展。
#   2. Python 中没有自增/自减运算符（++ / --），要写 x += 1。
#   3. = 是赋值，== 是判断相等，切勿混淆（常见错误来源）。


# 四、比较（关系）运算符（Comparison Operators）
# 比较运算符用于比较两个值，返回布尔值 True 或 False。

#   ==    等于：值相等
#   !=    不等于
#   >     大于
#   <     小于
#   >=    大于等于
#   <=    小于等于

# 支持链式比较（这是 Python 特色），其他语言真是弱爆了：
#   1 < x < 10  等价于  1 < x and x < 10，但更简洁高效。

#【举个例子】
num1,num2 = 10,20
print( "num1 == num2 ,返回 ", num1 == num2 )
print( "num1 != num2 ,返回 ", num1 != num2 )
print( "num1 > num2 ,返回 ", num1 > num2 )
print( "num1 < num2 ,返回 ", num1 < num2 )
print( "num1 >= num2 ,返回 ", num1 >= num2 )
print( "num1 <= num2 ,返回 ", num1 <= num2 )

# 【注意事项】
#   1. == 比较的是"值"，is 比较的是"身份（内存地址）"，二者语义不同。
#   2. 不同数据类型之间比较（如 1 == "1"）通常返回 False，不会报错。
#   3. 浮点数比较要小心精度问题，如 0.1 + 0.2 == 0.3 结果为 False，
#      建议用 math.isclose()。
#   4. 链式比较 a < b < c 只对 b 求值一次，效率更高。


