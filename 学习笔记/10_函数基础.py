# 函数
# 函数是组织好的、可重复使用的、用来实现特定功能的代码片段

# 【第一部分】函数定义
# 函数是把一段"完成某个特定功能"的代码封装起来，赋予一个名字，之后通过名字反复调用。
# 它解决的是"同样的逻辑写很多遍"的问题，让代码可以复用、拆分、便于维护。
# 关键语法点：
#   - 用关键字 def 定义函数，后面跟函数名、小括号、冒号。
#   - 函数体通过缩进（一般是 4 个空格）表示从属于该函数。
#   - 函数名命名遵循变量命名规则，推荐用下划线分隔的 snake_case 风格。
#   - 定义函数本身不会执行函数体，只有"调用"时才执行。
#   - 调用函数：函数名()，有参数则在括号里传值。
# 基本格式：
#   def 函数名(参数列表):
#       函数体
#       return 返回值
# 【举个例子】
print("---------------------------------------")
# 定义一个最简单的函数：无参数、无返回值
def say_hello():
    print("你好，幻想乡！")

# 调用函数
say_hello()
say_hello()   # 可以反复调用，代码只写一次

print("---------------------------------------")
# 带参数的函数
def greet(name):
    print(f"你好，{name}！")

greet("灵梦")
greet("魔理沙")

print("---------------------------------------")
# 带返回值的函数
def add(a, b):
    return a + b

result = add(3, 5)
print(result)          # 8

# 【注意事项】
#   1. def 那行末尾有冒号，函数体必须缩进，否则报 IndentationError。
#   2. 定义函数时不执行函数体，不调用就不会有任何效果。
#   3. 函数名不要和内置函数（如 list、print）重名，会覆盖内置函数。
#   4. 函数必须先定义、后调用（或调用时已定义），否则报 NameError。

print("---------------------------------------")

# 【第二部分】函数参数与返回值
# 参数解决的是"函数处理的数据从哪来"，返回值解决的是"函数处理完的结果往哪去"。
# 参数分类：
#   1. 位置参数：按顺序传入，最基础的形式。def f(a, b)  ->  f(1, 2)
#   2. 关键字参数：调用时用 参数名=值 指定，可以不按顺序。f(b=2, a=1)
#   3. 默认参数：定义时给参数默认值，调用时不传就用默认值。def f(a, b=10)
#   4. 可变位置参数 *args：把多余的位置参数收集成一个元组。
#   5. 可变关键字参数 **kwargs：把多余的关键字参数收集成一个字典。
# 返回值说明：
#   - 用 return 把结果返回给调用方，return 后面的代码不再执行。
#   - 没有 return 或 return 为空时，函数默认返回 None。
#   - return 可以一次返回多个值，本质是返回一个元组，可解包接收。
# 【举个例子】
print("---------------------------------------")
# 位置参数与关键字参数
def introduce(name, age):
    print(f"我叫{name}，今年{age}岁")

introduce("八云紫", 17)              # 位置参数：按顺序对应
introduce(age=17, name="八云紫")     # 关键字参数：顺序可颠倒

print("---------------------------------------")
# 默认参数
def power(base, exponent=2):
    return base ** exponent

print(power(5))         # 25，使用默认指数 2
print(power(5, 3))      # 125，传入 3 覆盖默认值

print("---------------------------------------")
# 可变位置参数 *args：收集多余位置参数为元组
def sum_all(*args):
    print(f"args 的类型是：{type(args)}")   # <class 'tuple'>
    return sum(args)

print(sum_all(1, 2, 3, 4))   # 10

print("---------------------------------------")
# 可变关键字参数 **kwargs：收集多余关键字参数为字典
def show_info(**kwargs):
    print(f"kwargs 的类型是：{type(kwargs)}")  # <class 'dict'>
    for key, value in kwargs.items():
        print(f"{key} -> {value}")

show_info(name="古明地觉", job="读心", home="地灵殿")

print("---------------------------------------")
# 返回单个值 / 多个值
def get_min_max(nums):
    return min(nums), max(nums)   # 实际返回一个元组

lo, hi = get_min_max([3, 1, 4, 1, 5])   # 解包接收
print(lo, hi)                    # 1 5

# 无返回值的函数，默认返回 None
def no_return():
    print("我什么都不返回")

print(no_return())               # 先打印提示，再打印 None

print("---------------------------------------")
# return 会立即结束函数
def check(n):
    if n < 0:
        return "负数"
    return "非负数"

print(check(-5))   # 负数
print(check(5))    # 非负数

# 【注意事项】
#   1. 默认参数最好用不可变对象，不要用 []、{} 等可变对象，否则会出现"默认值陷阱"，
#      因为默认值只在定义时创建一次，多次调用会共享同一个对象。
#   2. 位置参数必须放在关键字参数前面，否则报 SyntaxError。
#   3. *args 必须在普通参数和默认参数之后，**kwargs 必须放在最后。
#   4. return 一次返回多个值，接收方可用多个变量解包，也可用单个变量接住整个元组。
#   5. 函数执行到 return 就结束，后面的代码不会执行。

print("---------------------------------------")

# 【第三部分】函数说明文档（docstring）
# 说明文档是写在函数内部第一行的字符串，用来说明函数的功能、参数、返回值。
# 它不同于注释（#）：注释是给写代码的人看的，会被解释器忽略；
# 而 docstring 会保存在函数的 __doc__ 属性里，可以被工具、IDE 读取和展示。
# 关键语法点：
#   - 位置：必须是函数体的第一条语句。
#   - 写法：用三引号（""" """）包裹，可多行。
#   - 查看：函数.__doc__ 或 help(函数)。
#   - 推荐包含：功能描述、参数说明、返回值说明。
# 基本格式：
#   def 函数名(参数):
#       """功能描述
#       :param 参数: 参数说明
#       :return: 返回值说明  
#       """
# 【举个例子】
print("---------------------------------------")
def divide(a, b):
    """计算两个数的商

    :param a: 被除数
    :param b: 除数，不能为 0
    :return: a 除以 b 的结果
    """
    if b == 0:
        return None
    return a / b

# 查看函数说明文档
print(divide.__doc__)
print("---------------------------------------")
help(divide)    # help 会格式化输出文档内容

# 【注意事项】
#   1. docstring 必须写在函数体的第一行，写在其他位置无效。
#   2. 用三引号，尤其是多行说明时；单行也可用三引号或普通字符串。
#   3. 良好的文档能提升代码可读性，是团队协作和后期维护的重要习惯。

print("---------------------------------------")

# 【第四部分】函数嵌套调用
# 函数嵌套调用指的是：在一个函数内部调用另一个函数，形成调用链。
# 它让复杂功能可以拆成多个小函数，各自负责一部分，再组合起来使用。
# 注意区分两个概念：
#   1. 函数嵌套调用：在 A 函数里"调用" B 函数（A 调 B，B 执行完返回 A）。
#   2. 函数嵌套定义：在 A 函数里"定义" B 函数（B 是 A 的内部函数，涉及闭包）。
# 这里主要讲嵌套调用。
# 关键语法点：
#   - 调用链中，被调用函数先执行完并返回结果，调用方再继续。
#   - 嵌套调用可以有多层，但要控制层级，避免逻辑过于复杂。
#   - 每个函数保持"只做一件事"，由外层函数组织调用顺序。
# 【举个例子】
print("---------------------------------------")
# 先定义若干小功能函数
def function_a():                                     #最先入栈，最后出栈
    print("我是八云紫，我将调用八云蓝")                 #1
    function_b()
    print("我是八云紫，我完成了对八云蓝的调用")          #5

def function_b():                                     #中间入栈，中间出栈
    print("我是八云蓝，我将调用橙")                     #2
    function_c()
    print("我是八云蓝，我完成了对橙的调用")              #4

def function_c():                                     #最后入栈，最先出栈
    print("我是橙")                                    #3

# 嵌套调用：main 里依次调用其他函数
function_a()

print("---------------------------------------")
# 函数作为参数被传入（也是嵌套调用的延伸用法）
def apply_twice(func, x):
    return func(func(x))   # 在函数内调用传入的函数

def inc(n):
    return n + 1

print(apply_twice(inc, 5))  # inc(inc(5)) = 7

# 【注意事项】
#   1. 嵌套调用存在调用链：最内层先执行，逐层返回，理解执行顺序很重要。
#   2. 函数内可以调用任意已定义的其他函数，也可以调用自身（递归），但递归要有终止条件。
#   3. 把大功能拆成小函数再嵌套调用，是"函数化/模块化"的核心思想。
#   4. 避免过深的嵌套调用链，否则调试困难；必要时用中间变量记录每步结果。

print("---------------------------------------")
# 【知识点速查】
#   函数定义：def 函数名(参数): 函数体 ；先定义后调用，调用才执行。
#   参数类型：位置参数、关键字参数、默认参数、*args、**kwargs。
#   返回值：return 返回结果并结束函数；无 return 返回 None；可返回多值（元组）。
#   说明文档：函数体第一行三引号字符串，用 .__doc__ 或 help() 查看。
#   嵌套调用：函数内调用其他函数，形成调用链，实现功能拆分与组合。
