# Python模块
# 模块是Python中组织代码的一种方式，它允许我们将相关的函数、类和变量放在一个文件中，从而提高代码的可维护性和可重用性。
# 我们之前写过的Python文件其实就是一个个模块，我们可以通过import语句来导入模块，从而使用模块中的函数、类和变量。
# Python标准库中包含了许多内置模块，比如math、random、os、sys等，我们可以直接使用这些模块，而不需要自己编写代码。
# 我们也可以自己编写模块，只需要将相关的函数、类和变量放在一个.py文件中，然后通过import语句导入模块即可。

# 模块化的好处
# 1. 提高代码的可维护性：将相关的函数、类和变量放在一个模块中，可以让代码更容易理解和维护。
# 2. 提高代码的可重用性：将相关的函数、类和变量放在一个模块中，可以让代码更容易被其他程序使用，从而提高代码的可重用性。
# 3. 避免命名冲突：将相关的函数、类和变量放在一个模块中，可以避免命名冲突，从而提高代码的可读性和可维护性。