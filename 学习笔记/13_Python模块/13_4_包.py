# 软件包
# 软件包的本质是一个文件夹，这个文件夹下可以包含若干个python模块（.py文件，你可以看看左边的资源管理器）
# 文件夹下还包含了一个__init__.py，只有存在这个文件才能说是一个软件包。
# 作用：模块文件较多时，用来管理多个模块（其实软件包就是一个大模块，下辖诸多小模块。小模块下辖诸多具体功能）

# 包的有以下几种导入方式：
# 1,2,3为导入模块，4,5为导入功能

# 1. import 包名.模块名
# 2. form 包名 import 模块名
# 3. form 包名 import *
# 如果通过3导入包下的所有模块，需要在__init__.py文件中添加__all__=[]，指定这个“*”指定了哪些模块。


# 4. form 包名.模块名 import 功能名
# 5. form 包名.模块名 import *
