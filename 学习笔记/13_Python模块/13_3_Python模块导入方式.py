# Python模块
# 模块是Python中组织代码的一种方式，它允许我们将相关的函数、类和变量放在一个文件中，从而提高代码的可维护性和可重用性。
# 我们之前写过的Python文件其实就是一个个模块，我们可以通过import语句来导入模块，从而使用模块中的函数、类和变量。
# Python标准库中包含了许多内置模块，比如math、random、os、sys等，我们可以直接使用这些模块，而不需要自己编写代码。
# 我们也可以自己编写模块，只需要将相关的函数、类和变量放在一个.py文件中，然后通过import语句导入模块即可。



# 模块化的好处
# 1. 提高代码的可维护性：将相关的函数、类和变量放在一个模块中，可以让代码更容易理解和维护。
# 2. 提高代码的可重用性：将相关的函数、类和变量放在一个模块中，可以让代码更容易被其他程序使用，从而提高代码的可重用性。
# 3. 避免命名冲突：将相关的函数、类和变量放在一个模块中，可以避免命名冲突，从而提高代码的可读性和可维护性。



# 模块的导入
# 在使用模块中提供的功能之前，我们需要先导入模块。
# 导入模块的方式有多种，最常用的方式是使用import语句。
# 有以下几种导入模块的方式：

# 1. import 模块名：导入整个模块，可以使用模块名.函数名的方式来调用模块中的函数。
# 调用方式：
# import math
# math.sqrt(16)  # 调用math模块中的sqrt函数，计算16的平方根

# 2. import 模块名 as 别名：导入整个模块，并为模块指定一个别名，可以使用别名.函数名的方式来调用模块中的函数。
# 调用方式:
# import math as m
# m.sqrt(16)  # 调用math模块中的sqrt函数，计算16的平方根

# 3. from 模块名 import 功能名：只导入模块中的特定功能，可以直接使用函数名来调用。
# 调用方式:
# from math import sqrt
# sqrt(16)  # 调用math模块中的sqrt函数，计算16的平方根
# 这里不需要写作 math.sqrt(16)，因为我们只导入了sqrt函数，所以可以直接使用sqrt(16)来调用。

# 4. from 模块名 import 功能名 as 别名：只导入模块中的特定功能，并为功能指定一个别名，可以直接使用别名来调用。
# 调用方式:
# from math import sqrt as square_root
# square_root(16)  # 调用math模块中的sqrt函数，计算16的平方根

# 5. from 模块名 import *：导入模块中的所有功能，可以直接使用函数名来调用。
# 调用方式:
# from math import *
# sqrt(16)  # 调用math模块中的sqrt函数，计算16的平方根
# 如果前后导入的两个模块中有相同名称的方法，则后导入的会覆盖先导入的