# 面向过程编程
# 我们之前写过的诸多例子，都是面向过程编程
# 我们把一个需求拆分为一系列需要执行的步骤，然后按照步骤依次执行这些任务。核心关注点是流程和步骤。
# 面向过程编程非常直接，适用于简单和线性的任务。

# 面向对象编程
# 对象可用理解为现实中具体的人或物在程序中的数字化身。
# 你是一个对象，我也是一个对象，汽车是对象，火焰是对象，帝皇也是对象，奈亚拉托提普也是对象。
# 对象把一个人或物的特征（属性）和功能（方法）打包到一起，是面向对象编程的基本单元。

# 类与对象
# 类：描述的是一组具有相同属性（特征）和方法（功能、行为）
# 对象：对象是类的实力，是基于类创造出来的具体物，同一个类可以创建出无数对象
# 举个例子：
# 人类，他们有一双眼睛一张嘴，两只胳膊两条腿，他们毫无希望，生活方式是在泥地里打滚
# 奈亚拉托提普对象，他就有一双眼睛一张嘴，两只胳膊两条腿，他的生活毫无希望，生活方式是在泥地里打滚
