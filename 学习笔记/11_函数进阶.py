# 函数进阶



# 函数作用域
# 函数作用域指的是变量的作用范围，即在哪里可以使用，哪里不能使用
# 全局变量与局部变量
# 全局变量是指在函数外定义的变量，在整个文件的任意位置(包括函数内)都可以进行访问
# 局部变量是指在函数内定义的变量，只能在函数内部使用，无法在函数外使用。当函数执行完毕时，会销毁其内部所有的局部变量

print("---------------------------------------")
# 定义一个全局变量num1，作为圆的半径
num1 = 10

# 定义一个函数area()，用于计算圆的面积
# 函数中有三个局部变量：pi为圆周率，s为面积，r为需要传入的半径值
def area(r):
    pi = 3.14
    s = pi * r * r

    # 在函数内打印三个局部变量的值
    print("当前圆的半径为 = ", r)
    print("当圆周率取值为 = ", pi)
    print("当前圆的面积为 = ", s)
    # 现在我们在函数中修改num1的值
    num1 = 2000
    print("在函数中修改num后，num值为 = ",num1)
    return(s)

# 由于局部变量在函数外部无法访问，在这里访问将会产生报错
#print("当前圆的半径为 = ", r)
#print("当圆周率取值为 = ", pi)
#print("当前圆的面积为 = ", s)

circle1_s = area(num1)
# 现在我们看看在第一个函数运行后，num1的值：
print("在函数area运行后，num1的值为 =",num1)
print(circle1_s)
# num1的值依然为10，这是因为函数内的num1事实上是哟个一个新的局部变量，对其做出的修改与全局变量无关

# 当然，python中存在关键字global,当使用它时，就相当于告诉解释器，要指定用全局变量，这时就可以对全局变量进行修改
# 如果要使用global关键字，就必须先声明再使用
def global_num():
    # 用global关键字修饰，使用全局变量num1
    global num1
    num1 = 20
    return num1

print("---------------------------------------")
global_num()
print("经过带有global关键字修饰的函数后，num1的值为 = ",num1)



# 函数参数详解

# 函数传参方式
# 函数传参方式是指，在调用参数时，传递参数的方式。

# 位置参数
# 调用函数时，根据定义的位置来传递参数
print("---------------------------------------")
def reg1(name, age, home):
    print(f"你的名字是{name}，年龄是{age}，家住在{home}。")
    return{"name": name, "age": age, "home":home}
# 给函数的参数赋值时，根据函数中变量定义的位置进行一一对应的赋值，如name-射命丸文，age-18，home-妖怪之山
stu1 = reg1("射命丸文",18,"妖怪之山")
print(stu1)

# 关键字参数
# 调用函数时以函数定义时形参名称作为关键字，以键值对的形式传递参数(不需要按顺序)
print("---------------------------------------")
def reg2(name, age, home):
    print(f"你的名字是{name}，年龄是{age}，家住在{home}。")
    return{"name": name, "age": age, "home":home}
# 注意，混用位置参数和关键字参数时，必须先用位置参数，后用关键字参数。关键字参数之间没有顺序要求。
stu2 = reg2("因幡帝",home="迷途竹林",age=15)
print(stu2)