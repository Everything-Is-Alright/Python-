# 类型注解
# 类型注解是Python 3.5+引入的一个特性，它允许我们在定义变量、函数参数和返回值时指定它们的类型。
# 我想，如果你学习过其他编程语言，比如Java、C#，你可能会觉得类型注解很熟悉，因为这些语言都是强类型语言，而Python是动态类型语言。
# 类型注解的语法格式为：
# 变量类型注解：变量名: 类型 = 值
# 函数类型注解：def 函数名(参数名: 类型) -> 返回值类型:
# 类型注解不会影响代码的运行，它只是给开发者和工具提供类型信息

# 举个例子
print("---------------------------------------")
# 定义不同类型的变量
name: str = "蕾米莉亚"
age: int = 500
height: float = 1.75
is_student: bool = False
name_list: list[str] = ["蕾米莉亚", "芙兰朵露", "咲夜"]
print(f"姓名：{name}，年龄：{age}，身高：{height}，是否是学生：{is_student}，名字列表：{name_list}")
# 联合类型注解
# 如果一个变量可以是多种类型，我们可以使用联合类型注解，语法格式为：
# 变量名: 类型1 | 类型2 = 值
sorce : int | float = 95.5
print(f"分数：{sorce}")

# 类型推断
# Python是一种动态类型语言，它会根据变量的值自动推断出变量的类型，所以我们可以省略类型注解，直接定义变量。
# 但是，如果我们想要明确指定变量的类型，我们可以使用类型注解。

# 定义函数时的类型注解
print("---------------------------------------")
def greet(name: str) -> str:
    return f"Hello, {name}!"
print(greet("蕾米莉亚"))